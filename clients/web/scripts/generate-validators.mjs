import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(scriptDirectory, "..");
const schemaPath = resolve(webRoot, "src/api/generated/v1.schema.json");
const javascriptPath = resolve(
  webRoot,
  "src/api/generated/v1.validators.js",
);
const declarationsPath = resolve(
  webRoot,
  "src/api/generated/v1.validators.d.ts",
);

const schemaId = "https://rstorrent.invalid/schemas/api/v1";
const validators = {
  validateApiHello: "ApiHello",
  validateApplicationServerFrame: "ApplicationServerFrame",
  validateResponseEnvelope: "ResponseEnvelope",
  validateApiErrorEnvelope: "ApiErrorEnvelope",
  validateChooseDownloadRootResponse: "ChooseDownloadRootResponse",
  validateOpenViewSetResponse: "OpenViewSetResponse",
  validateUpdateBatch: "UpdateBatch",
};

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  validateFormats: false,
  // Share larger referenced definitions across the exported entry points.
  inlineRefs: 3,
  code: {
    esm: true,
    optimize: true,
    source: true,
  },
});
ajv.addSchema(schema, schemaId);

const references = Object.fromEntries(
  Object.entries(validators).map(([exportName, definition]) => [
    exportName,
    `${schemaId}#/$defs/${definition}`,
  ]),
);
for (const [exportName, reference] of Object.entries(references)) {
  if (ajv.getSchema(reference) === undefined) {
    throw new Error(`${exportName} references missing schema ${reference}`);
  }
}

const generatedHeader =
  "// Generated by npm run generate:validators. Do not edit.\n";
const standaloneJavascript = standaloneCode(ajv, references).replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  "const $1 = (value) => Array.from(value).length;",
);
if (/\brequire\s*\(/.test(standaloneJavascript)) {
  throw new Error(
    "AJV generated a CommonJS runtime dependency for the browser validator",
  );
}
const javascript = `${generatedHeader}${standaloneJavascript}\n`;
const declarations = `${generatedHeader}
export interface StandaloneValidationError {
  readonly instancePath: string;
  readonly message?: string;
}

export interface StandaloneValidateFunction {
  (value: unknown): boolean;
  readonly errors?: readonly StandaloneValidationError[] | null;
}

${Object.keys(validators)
  .map(
    (exportName) =>
      `export const ${exportName}: StandaloneValidateFunction;`,
  )
  .join("\n")}
`;

await Promise.all([
  writeFile(javascriptPath, javascript, "utf8"),
  writeFile(declarationsPath, declarations, "utf8"),
]);
